def _prepare(run_dir: Path, sources: dict, steps: int, blocks_to_swap: int = 0) -> dict:
    workspace = run_dir / "train-workspace"
    images, cache = workspace / "images", workspace / "cache"
    images.mkdir(parents=True, exist_ok=True)
    cache.mkdir(parents=True, exist_ok=True)
    for index in range(2):
        w, h = IMAGE_SIZE
        Image.new("RGB", (w, h), color=(40 * index + 30, 70, 110)).save(images / f"img{index}.png")
        (images / f"img{index}.txt").write_text(f"1girl, solo, identity test {index}", encoding="utf-8")

    te_copy, vae_copy = workspace / "te.safetensors", workspace / "vae.safetensors"
    shutil.copy2(sources["te"], te_copy)
    shutil.copy2(sources["vae"], vae_copy)

    paths = {
        "workspace": workspace, "images": images, "cache": cache,
        "te": te_copy, "vae": vae_copy, "dit": sources["dit"],
        "runtime": workspace / "config.runtime.toml",
        "dataset": workspace / "dataset.toml",
        "output": workspace / "train_out",
        "logs": workspace / "train_out" / "logs",
    }
    paths["runtime"].write_text(RUNTIME_TOML.format(
        dit=sources["dit"], te=te_copy, vae=vae_copy, steps=steps,
        blocks_to_swap=blocks_to_swap,
        images=images, cache=cache, output=paths["output"], logs=paths["logs"],
    ), encoding="utf-8")
    paths["dataset"].write_text(
        DATASET_TOML.format(side=IMAGE_SIZE[0], images=images, cache=cache), encoding="utf-8"
    )
    return paths


def _run(cmd: list[str], *, gpu: int, log: Path) -> subprocess.CompletedProcess:
    env = {**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu), "PRESET": "default"}
    env.pop("METHOD", None)
    env.setdefault("PYTHONUNBUFFERED", "1")
    env.setdefault("TOKENIZERS_PARALLELISM", "false")
    proc = subprocess.run(cmd, cwd=REPO_ROOT, env=env, capture_output=True, text=True)
    log.write_text(proc.stdout + proc.stderr, encoding="utf-8")
    return proc


def _preprocess(paths: dict, kind: str, *, gpu: int, dtype: str, run_dir: Path) -> dict:
    common = ["--dir", str(paths["images"]), "--cache_dir", str(paths["cache"]),
              "--batch_size", "1", "--dtype", dtype, "--require_cache_identity"]
    if kind == "latents":
        module = "scripts.preprocess.cache_latents"
        extra = ["--vae", str(paths["vae"]), "--model_family", "anima"]
    else:
        module = "scripts.preprocess.cache_text_embeddings"
        extra = ["--qwen3", str(paths["te"]), "--dit", str(paths["dit"]),
                 "--min_pixels", "0", "--caption_shuffle_variants", "0"]
    proc = _run([PY, "-m", module, *common, *extra], gpu=gpu, log=run_dir / f"pre-{kind}.log")
    match = WROTE_RE.search(proc.stdout)
    written, skipped = (int(g) for g in match.groups()) if match else (None, None)
    return {"stage": f"preprocess_{kind}", "returncode": proc.returncode,
            "written": written, "skipped": skipped}


def _train(paths: dict, tag: str, *, gpu: int, run_dir: Path) -> dict:
    cmd = [PY, "train.py", "--config_file", str(paths["runtime"]),
           "--dataset_config", str(paths["dataset"])]
    proc = _run(cmd, gpu=gpu, log=run_dir / f"train-{tag}.log")
    text = proc.stdout + proc.stderr
    lorae = sorted(paths["output"].glob("*.safetensors"))
    return {"stage": f"train_{tag}", "returncode": proc.returncode,
            "te_error": TE_ERROR in text, "latent_error": LATENT_ERROR in text,
            "saved": [p.name for p in lorae]}


def _stamp(path: Path):
    if path.suffix == ".npz":
        import numpy as np
        with np.load(path) as npz:
            return json.loads(str(npz["cache_identity"].item())) if "cache_identity" in npz.files else None
    from safetensors import safe_open
    with safe_open(str(path), framework="pt") as handle:
        raw = (handle.metadata() or {}).get("cache_identity")
    return json.loads(raw) if raw else None


def _strip_stamps(paths: dict, kinds: tuple[str, ...]) -> int:
    """Rewrite the named sidecars as legacy (pre-identity) files."""
    import numpy as np
    from safetensors.torch import load_file, save_file

    stripped = 0
    if "latent" in kinds:
        for npz_path in sorted(paths["cache"].glob("*_anima.npz")):
            with np.load(npz_path) as npz:
                payload = {key: npz[key] for key in npz.files if key != "cache_identity"}
            np.savez(npz_path, **payload)
            stripped += 1
    if "te" in kinds:
        for te_path in sorted(paths["cache"].glob("*_anima_te.safetensors")):
            save_file(load_file(str(te_path)), str(te_path),
                      metadata={"model_family": "anima", "cache_schema": "anima_te_v1"})
            stripped += 1
    return stripped


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--steps", type=int, default=10)
    parser.add_argument("--blocks-to-swap", type=int, default=0,
                        help="0 keeps the hot test off the Anima block-swap path.")
    parser.add_argument("--dtype", default="bfloat16")
    parser.add_argument("--dit", default=DEFAULT_DIT)
    parser.add_argument("--te", default=DEFAULT_TE)
    parser.add_argument("--vae", default=DEFAULT_VAE)
    parser.add_argument("--root", default="output/bench/cache_identity_hot")
    args = parser.parse_args()

    sources = {"dit": str(Path(args.dit).expanduser()),
               "te": str(Path(args.te).expanduser()),
               "vae": str(Path(args.vae).expanduser())}
    for label, path in sources.items():
        if not Path(path).exists():
            print(f"missing {label}: {path}", file=sys.stderr)
            return 2

    run_dir = make_run_dir("cache_identity_hot", root=args.root)
    paths = _prepare(run_dir, sources, args.steps, blocks_to_swap=args.blocks_to_swap)
    os.utime(paths["te"], None)  # ensure the copy's mtime differs from the source

    stages: list[dict] = []
    def record(row: dict) -> dict:
        stages.append(row)
        print(json.dumps(row, ensure_ascii=False))
        return row

    record(_preprocess(paths, "latents", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    record(_preprocess(paths, "te", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    stamps_after_cache = {"latent": _stamp(next(iter(sorted(paths["cache"].glob("*.npz"))))),
                          "te": _stamp(next(iter(sorted(paths["cache"].glob("*_anima_te.safetensors")))))}

    record(_train(paths, "clean", gpu=args.gpu, run_dir=run_dir))

    os.utime(paths["te"], None)
    record(_train(paths, "te_changed", gpu=args.gpu, run_dir=run_dir))

    record(_preprocess(paths, "te", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    os.utime(paths["vae"], None)
    record(_train(paths, "vae_changed", gpu=args.gpu, run_dir=run_dir))

    # Rebuild the latents so only the TE identity is still stale, then prove
    # strict mode refuses unstamped sidecars one kind at a time.
    record(_preprocess(paths, "latents", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    stripped_te = _strip_stamps(paths, ("te",))
    record(_train(paths, "strict_legacy_te", gpu=args.gpu, run_dir=run_dir))

    record(_preprocess(paths, "te", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    stripped_latent = _strip_stamps(paths, ("latent",))
    record(_train(paths, "strict_legacy_latent", gpu=args.gpu, run_dir=run_dir))

    # Both kinds cancelled out: recovery is a normal preprocess + train.
    record(_preprocess(paths, "latents", gpu=args.gpu, dtype=args.dtype, run_dir=run_dir))
    record(_train(paths, "recovered", gpu=args.gpu, run_dir=run_dir))

    by_name = {row["stage"]: row for row in stages}
    failures = []
    def check(stage: str, predicate: bool, detail: str) -> None:
        if not predicate:
            failures.append(f"{stage}: {detail}")

    check("train_clean", by_name["train_clean"]["returncode"] == 0
          and bool(by_name["train_clean"]["saved"]), "expected a completed run with a saved LoRA")
    check("train_te_changed", by_name["train_te_changed"]["returncode"] != 0
          and by_name["train_te_changed"]["te_error"], "expected the TE-cache refusal")
    check("train_vae_changed", by_name["train_vae_changed"]["returncode"] != 0
          and by_name["train_vae_changed"]["latent_error"], "expected the latent-cache refusal")
    check("train_strict_legacy_te", by_name["train_strict_legacy_te"]["returncode"] != 0
          and by_name["train_strict_legacy_te"]["te_error"],
          "expected strict mode to refuse an unstamped TE cache")
    check("train_strict_legacy_latent", by_name["train_strict_legacy_latent"]["returncode"] != 0
          and by_name["train_strict_legacy_latent"]["latent_error"],
          "expected strict mode to refuse an unstamped latent cache")
    check("train_recovered", by_name["train_recovered"]["returncode"] == 0
          and bool(by_name["train_recovered"]["saved"]), "expected recovery after re-preprocess")

    metrics = {"stages": stages, "stamps_after_cache": stamps_after_cache,
               "stamps_stripped": {"te": stripped_te, "latent": stripped_latent},
               "passed": not failures, "failures": failures,
               "image_size": list(IMAGE_SIZE), "steps": args.steps,
               "blocks_to_swap": args.blocks_to_swap, "sources": sources}
    (run_dir / "train-stages.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    write_result(run_dir, script=__file__, args=args, metrics=metrics,
                 label="train-launch-identity", artifacts=["train-stages.json"],
                 device=f"cuda:{args.gpu}")
    print(f"\n{'PASS' if not failures else 'FAIL'} -> {run_dir}")
    for item in failures:
        print(f"  {item}")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
