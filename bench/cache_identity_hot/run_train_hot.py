#!/usr/bin/env python
"""Hot test: real train.py launch against identity-stamped caches.

Builds a throwaway 2-image / 512x512 dataset with the real Anima weights, caches
latents + text-encoder outputs through the real preprocess CLIs (so every sidecar
carries a model identity), then launches the real training entry point four
times:

1. build_latents_cache / build_te_cache   preprocess CLIs write both sidecars
2. train_clean                            caches complete -> trains and saves
3. train_te_changed                       TE identity changed -> fail closed
4. train_vae_changed                      VAE identity changed -> fail closed
5. train_strict_legacy                    stamps stripped + require_cache_identity
6. train_recovered                        rebuild -> trains again

train.py refuses to start on an incomplete cache ("... cache is incomplete ...
requires a completed preprocess pass"), so a changed encoder/VAE must abort the
launch instead of silently training on stale tensors.

Usage::

    .venv/bin/python -m bench.cache_identity_hot.run_train_hot --gpu 0 --steps 10
"""

