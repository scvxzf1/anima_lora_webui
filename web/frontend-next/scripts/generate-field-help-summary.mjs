import { readFile, writeFile } from "node:fs/promises";
import { FIELD_HELP_ZH } from "../src/features/training-config/domain/field-help.js";

const destination = new URL("../src/features/training-config/domain/field-help-summary.js", import.meta.url);
const summaries = Object.fromEntries(Object.entries(FIELD_HELP_ZH).map(([key, help]) => [key, help.summary]));
const source = "// Generated by scripts/generate-field-help-summary.mjs; edit the full help catalog instead.\n\n"
  + "export const FIELD_HELP_SUMMARY_ZH = Object.freeze(" + JSON.stringify(summaries, null, 4) + ");\n";

if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== source) {
    console.error("Help summaries are out of date. Run node scripts/generate-field-help-summary.mjs.");
    process.exitCode = 1;
  } else {
    console.log(`Help summaries aligned: ${Object.keys(summaries).length} fields.`);
  }
} else {
  await writeFile(destination, source);
  console.log(`Generated ${Object.keys(summaries).length} help summaries.`);
}
