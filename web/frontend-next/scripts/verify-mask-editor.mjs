  expect(await strokePixel()).toEqual(transparent);
  await command('黑白蒙版');
  expect(await strokePixel()).toEqual([255, 255, 255, 255]);
  await command('叠加预览');
  checks.push('transparent=training; tinted=ignored; brush black and eraser white pixels');
  await command('撤销');
  await command('重做');
  await command('撤销');
  await command('反选');
  await command('撤销');
  await command('放大');
  await command('缩小');
  await command('平移');
  await draw();
  await command('适应画布');
  checks.push('brush/eraser/undo/redo/invert/zoom/pan');
  await page.getByRole('button', { name: /^garment-02\.png/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await command('继续编辑');
  await expect(page.getByText('未保存', { exact: true })).toBeVisible();
