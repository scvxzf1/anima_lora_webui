import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const target = process.env.MASK_HOT_URL || 'http://127.0.0.1:20541';
const output = process.env.MASK_HOT_OUTPUT || '/tmp/dragon-mask-hot-check';
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(target)) throw new Error('Loopback fixture required');
const fixture = await fetch(`${target}/api/mask-hot-fixture`).then(response => response.json());
if (fixture.isolated !== true) throw new Error('Refusing writes outside the isolated fixture');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const errors = [];
const checks = [];
const file = 'configs/datasets/mask-hot-test.toml';
const url = `${target}/next/datasets?${new URLSearchParams({ dataset: file })}`;
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
async function command(name) { await page.getByRole('button', { name, exact: true }).click(); }
async function strokePixel() {
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  return page.getByLabel('蒙版编辑画布').evaluate(canvas => [...canvas.getContext('2d')
    .getImageData(Math.floor(canvas.width * .42), Math.floor(canvas.height * .45), 1, 1).data]);
}
async function draw() {
  const canvas = page.getByLabel('蒙版编辑画布');
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x + box.width * .42, box.y + box.height * .45);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .60, box.y + box.height * .6, { steps: 12 });
  await page.mouse.up();
}
