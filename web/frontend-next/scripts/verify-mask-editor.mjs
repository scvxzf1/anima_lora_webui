import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const target = process.env.MASK_HOT_URL || 'http://127.0.0.1:20541';
const output = process.env.MASK_HOT_OUTPUT || '/tmp/dragon-mask-hot-check';
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(target)) throw new Error('Loopback fixture required');
const fixture = await fetch(`${target}/api/mask-hot-fixture`).then(response => response.json());
if (fixture.isolated !== true) throw new Error('Refusing writes outside the isolated fixture');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const errors = [];
const checks = [];
const file = 'configs/datasets/mask-hot-test.toml';
const url = `${target}/next/datasets/masks?${new URLSearchParams({ dataset: file })}`;
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
async function command(name) { await page.getByRole('button', { name, exact: true }).click(); }
async function draw() {
  const canvas = page.getByLabel('蒙版编辑画布');
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x + box.width * .42, box.y + box.height * .45);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .60, box.y + box.height * .6, { steps: 12 });
  await page.mouse.up();
}
try {
  await page.goto(url);
  await expect(page.getByRole('button', { name: '清空', exact: true })).toBeEnabled();
  await command('清空');
  await draw();
  await expect(page.getByText('未保存', { exact: true })).toBeVisible();
  await command('橡皮擦（黑色忽略）');
  await draw();
  await command('撤销');
  await command('重做');
  await command('撤销');
  await command('反选');
  await command('撤销');
  await command('放大');
  await command('缩小');
  await command('平移');
  await draw();
  await command('适应画布');
  checks.push('brush/eraser/undo/redo/invert/zoom/pan');
  await page.getByRole('button', { name: /^garment-02\.png/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await command('继续编辑');
  await expect(page.getByText('未保存', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: '返回数据集', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await command('继续编辑');
  checks.push('dirty image-switch and route protection');
  const saved = page.waitForResponse(response => response.url().includes('/dataset-masks/image') && response.request().method() === 'PUT');
  await command('保存');
  expect((await saved).status()).toBe(200);
  await expect(page.getByText('蒙版已保存', { exact: true })).toBeVisible();
  await command('重新加载蒙版');
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveText('已保存');
  await command('黑白蒙版');
  const pixels = await page.getByLabel('蒙版编辑画布').evaluate(canvas => {
    const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
    let black = 0, white = 0;
    for (let i = 0; i < data.length; i += 4) {
      if (data[i + 3] && data[i] === 0) black++;
      if (data[i + 3] && data[i] === 255) white++;
    }
    return { black, white };
  });
  expect(pixels.black).toBeGreaterThan(1000);
  expect(pixels.white).toBeGreaterThan(100);
  checks.push({ savedReloadCanvasPixels: pixels });
  await command('叠加预览');
  await command('应用到子集');
  const applied = page.waitForResponse(response => response.url().includes('/dataset-masks/apply'));
  await command('确认应用');
  expect((await applied).status()).toBe(200);
  await expect(page.getByText('外部蒙版已启用', { exact: true })).toBeVisible();
  checks.push('real HTTP mask save/reload and subset apply');
  await expect(page.getByRole('button', { name: '清空', exact: true })).toBeEnabled();
  await command('画笔（白色参与训练）');
  await page.screenshot({ path: `${output}/desktop.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  const peer = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  peer.on('pageerror', error => errors.push(error.message));
  await peer.goto(url);
  await expect(peer.getByRole('button', { name: '反选', exact: true })).toBeEnabled();
  await peer.getByRole('button', { name: '反选', exact: true }).click();
  await command('反选'); await command('保存');
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveText('已保存');
  const conflict = peer.waitForResponse(response => response.url().includes('/dataset-masks/image') && response.request().method() === 'PUT');
  await peer.getByRole('button', { name: '保存', exact: true }).click();
  expect((await conflict).status()).toBe(409);
  await expect(peer.getByRole('alert')).toContainText('已变化');
  await expect(peer.getByText('未保存', { exact: true })).toBeVisible();
  await peer.close();
  await command('反选'); await command('保存');
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveText('已保存');
  checks.push('two-tab stale write rejected; unsaved edit retained');
  await page.getByRole('button', { name: /^garment-02\.png/ }).click();
  await expect(page.getByRole('button', { name: '全选', exact: true })).toBeEnabled();
  await command('清空');
  await page.getByRole('button', { name: /^garment-03\.png/ }).click();
  await command('放弃修改并继续');
  await expect(page.locator('.mask-filename')).toHaveText('garment-03.png');
  await expect(page.getByRole('button', { name: '清空', exact: true })).toBeEnabled();
  checks.push('discard and continue');
  await page.setViewportSize({ width: 390, height: 844 });
  await command('展开或收起蒙版工具');
  await command('适应画布');
  await page.waitForTimeout(150);
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await command('清空');
  await draw();
  await command('保存');
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveText('已保存');
  await command('展开或收起蒙版工具');
  await page.screenshot({ path: `${output}/mobile-canvas.png`, fullPage: true });
  await command('展开或收起图片列表');
  await page.screenshot({ path: `${output}/mobile-images.png`, fullPage: true });
  await page.getByRole('button', { name: /^garment-01\.png/ }).click();
  await expect(page.locator('.mask-filename')).toHaveText('garment-01.png');
  checks.push('mobile canvas draw/save/image list; no horizontal overflow');
  expect(errors).toEqual([]);
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png`, fullPage: true });
  console.log(await page.locator('body').innerText());
  throw error;
} finally {
  await writeFile(`${output}/report.json`, JSON.stringify({ fixture, checks, errors }, null, 2));
  await browser.close();
  console.log(JSON.stringify({ output, checks, errors }, null, 2));
}
