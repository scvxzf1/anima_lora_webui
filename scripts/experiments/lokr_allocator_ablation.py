#!/usr/bin/env python3
"""Generate and optionally run LoKr 16G allocator ablation configs.

The current LoKr 16G bottleneck is no longer H2D wait and the no-kron/fused
LoKr path already reduces max allocated. The remaining target is allocator
reserved/free headroom. This script clones a known-good runtime TOML and emits
short-run variants that differ only by PYTORCH_CUDA_ALLOC_CONF.

Default mode only writes configs and prints exact commands. Use --run to execute
sequentially.
"""

from __future__ import annotations

import argparse
import os
import shlex
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_TEMPLATE_CANDIDATES = [
    Path("/tmp/anima-lokr-peak-probe/F0_fused_lokr_add_g8_50.runtime.toml"),
    Path("/tmp/anima-lokr-peak-probe/B0_baseline_g8_current_50.runtime.toml"),
]
DEFAULT_OUT_DIR = Path("/tmp/anima-lokr-allocator-ablation")

CASES: list[dict[str, str]] = [
    {
        "name": "alloc256_baseline",
        "desc": "当前推荐 fallback，作为 allocator 对照。",
        "alloc_conf": "expandable_segments:True,max_split_size_mb:256",
    },
    {
        "name": "alloc128",
        "desc": "降低 split size，观察 reserved/free 是否改善。",
        "alloc_conf": "expandable_segments:True,max_split_size_mb:128",
    },
    {
        "name": "alloc64_gc08",
        "desc": "更激进 split + cache GC，复测 F1 是否能稳定提升最低 free。",
        "alloc_conf": "expandable_segments:True,max_split_size_mb:64,garbage_collection_threshold:0.8",
    },
    {
        "name": "alloc32_gc08",
        "desc": "最激进 allocator 候选；若速度/碎片恶化则淘汰。",
        "alloc_conf": "expandable_segments:True,max_split_size_mb:32,garbage_collection_threshold:0.8",
    },
]


def _python() -> str:
    candidate = ROOT / ".venv" / "bin" / "python"
    return str(candidate if candidate.exists() else Path(sys.executable))


def _default_template() -> Path:
    for path in DEFAULT_TEMPLATE_CANDIDATES:
        if path.exists():
            return path
    raise SystemExit(
        "No default LoKr runtime template found. Pass --template explicitly."
    )


def _toml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f"{value:.12g}"
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def _write_toml(path: Path, data: dict[str, Any]) -> None:
    variant = data.pop("variant", None)
    lines = [
        "# Auto-generated by scripts/experiments/lokr_allocator_ablation.py",
        "# Template-derived runtime config for LoKr 16G allocator ablation.",
        "",
    ]
    for key in sorted(data):
        lines.append(f"{key} = {_toml_scalar(data[key])}")
    if isinstance(variant, dict):
        lines.extend(["", "[variant]"])
        for key in sorted(variant):
            lines.append(f"{key} = {_toml_scalar(variant[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _case_config(template: dict[str, Any], case: dict[str, str], *, out_dir: Path, steps: int) -> Path:
    name = case["name"]
    cfg = dict(template)
    cfg["variant"] = dict(template.get("variant") or {})
    cfg.update(
        {
            "max_train_steps": int(steps),
            "blocks_to_swap": 23,
            "block_swap_transfer_dtype": "bf16",
            "selective_checkpoint": "off",
            "gradient_checkpointing": False,
            "unsloth_offload_checkpointing": False,
            "torch_compile": True,
            "attn_mode": "flash",
            "lokr_factor_group_size": 8,
            "output_name": f"anima_lokr_{name}_{steps}",
            "output_dir": str(out_dir / f"{name}_output"),
            "logging_dir": str(out_dir / f"{name}_logs"),
            "progress_jsonl": str(out_dir / f"{name}.progress.jsonl"),
            "memory_probe_jsonl": str(out_dir / f"{name}.memory_probe.jsonl"),
            "memory_probe_max_steps": int(steps),
            "peak_probe_jsonl": str(out_dir / f"{name}.peak_probe.jsonl"),
            "peak_probe_max_steps": int(steps),
            "peak_probe_level": "block",
            "block_swap_profile_jsonl": str(out_dir / f"{name}.block_swap_profile.jsonl"),
            "sample_every_n_steps": 0,
            "sample_every_n_epochs": 0,
            "save_every_n_epochs": 9999,
        }
    )
    cfg_path = out_dir / f"{name}.runtime.toml"
    _write_toml(cfg_path, cfg)
    return cfg_path


def _command(cfg_path: Path, case: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    env = os.environ.copy()
    env["PYTORCH_CUDA_ALLOC_CONF"] = case["alloc_conf"]
    cmd = [_python(), "train.py", "--config_file", str(cfg_path)]
    return env, cmd


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template", type=Path, default=None, help="Known-good runtime TOML to clone")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument("--only", default="", help="Run/generate only cases whose name contains this text")
    parser.add_argument("--run", action="store_true", help="Execute cases sequentially after writing configs")
    args = parser.parse_args()

    template_path = args.template or _default_template()
    with template_path.open("rb") as fh:
        template = tomllib.load(fh)

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    selected = [case for case in CASES if not args.only or args.only in case["name"]]
    if not selected:
        raise SystemExit(f"No cases matched --only={args.only!r}")

    print(f"LoKr allocator ablation: template={template_path}")
    print(f"out_dir={out_dir} steps={args.steps} cases={len(selected)}")
    for case in selected:
        cfg_path = _case_config(template, case, out_dir=out_dir, steps=args.steps)
        env, cmd = _command(cfg_path, case)
        printable = " ".join(shlex.quote(part) for part in cmd)
        print(f"\n[{case['name']}] {case['desc']}")
        print(f"  PYTORCH_CUDA_ALLOC_CONF={case['alloc_conf']}")
        print(f"  config: {cfg_path}")
        print(f"  cmd: PYTORCH_CUDA_ALLOC_CONF={shlex.quote(case['alloc_conf'])} {printable}")
        if args.run:
            subprocess.run(cmd, cwd=ROOT, env=env, check=True)
    if not args.run:
        print("\nGenerated configs only. Add --run to execute sequentially.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
