def _python_for_tasks() -> str:
    candidate = ROOT / ".venv" / "bin" / "python"
    if candidate.exists():
        return str(candidate)
    return sys.executable


def _toml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f"{value:.12g}"
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def _write_flat_toml(path: Path, data: dict[str, Any], variant: dict[str, Any]) -> None:
    lines = [
        "# Auto-generated by scripts/experiments/vera_short_ablation.py",
        "# Safe to overwrite. Edit configs/gui-methods/vera.toml for the base VeRA preset.",
        "",
    ]
    for key in sorted(data):
        lines.append(f"{key} = {_toml_scalar(data[key])}")
    lines.extend(["", "[variant]"])
    for key in sorted(variant):
        lines.append(f"{key} = {_toml_scalar(variant[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def case_config(
    case: dict[str, Any],
    *,
    steps: int,
    sample_every: int,
    save_every: int,
    dataset_config: str | None,
    output_dir: str,
) -> tuple[str, dict[str, Any], dict[str, Any]]:
    variant_name = f"vera_ablate_{case['name']}"
    cfg = {
        "network_dim": case["network_dim"],
        "network_alpha": case["network_alpha"],
        "learning_rate": case["learning_rate"],
        "max_train_steps": int(steps),
        "save_every_n_steps": int(save_every),
        "checkpointing_steps": int(save_every),
        "sample_every_n_steps": int(sample_every),
        "logging_dir": LOG_DIR,
        "output_dir": output_dir,
        "output_name": f"anima_vera_ablate_{case['name']}",
        "use_shuffled_caption_variants": True,
        "cache_llm_adapter_outputs": True,
        "caption_dropout_rate": 0.1,
        "use_vera": True,
        "vera_save_projection": False,
        "vera_projection_prng_key": case["vera_projection_prng_key"],
        "vera_d_initial": case["vera_d_initial"],
        "rank_dropout": case["rank_dropout"],
        "use_timestep_mask": case["use_timestep_mask"],
        "alpha_rank_scale": 1.0,
        "blocks_to_swap": 0,
        "use_cmmd": False,
        "network_train_unet_only": True,
        "config_snapshot": True,
    }
    if "min_rank" in case:
        cfg["min_rank"] = case["min_rank"]
    if dataset_config:
        cfg["dataset_config"] = dataset_config
    meta = {
        "family": "lora",
        "label": f"VeRA ablation: {case['name']}",
        "description": case["desc"],
        "order": 90,
    }
    return variant_name, cfg, meta


def build_cmd(variant_name: str, *, preset: str, queue: bool) -> list[str]:
    cmd = [_python_for_tasks(), "tasks.py", "lora-gui", variant_name]
    if preset:
        # PRESET env is also set when running; this comment-friendly command keeps
        # copy/paste explicit for shell users.
        pass
    if queue:
        cmd.append("--queue")
    return cmd


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=120, help="每个 case 的短训步数")
    parser.add_argument("--sample-every", type=int, default=60, help="每 N step 出样图")
    parser.add_argument("--save-every", type=int, default=120, help="每 N step 保存 checkpoint")
    parser.add_argument("--preset", default="default", help="继承的硬件 preset")
    parser.add_argument("--dataset-config", default=None, help="可选数据集 TOML，例如 configs/datasets/xxx.toml")
    parser.add_argument("--output-dir", default="output/ckpt", help="checkpoint 输出目录")
    parser.add_argument("--only", default=None, help="只生成/运行名称包含该子串的 case")
    parser.add_argument("--queue", action="store_true", help="提交到 daemon 队列")
    parser.add_argument("--run", action="store_true", help="实际执行；默认只打印计划")
    args = parser.parse_args()

    selected = [case for case in CASES if args.only is None or args.only in case["name"]]
    if not selected:
        raise SystemExit(f"No cases matched --only={args.only!r}")

    print("\n🧪 VeRA 短期消融计划")
    print(f"- cases: {len(selected)}")
    print(f"- steps/case: {args.steps}")
    print(f"- preset: {args.preset}")
    if args.dataset_config:
        print(f"- dataset_config: {args.dataset_config}")
    print("")

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    for idx, case in enumerate(selected, 1):
        variant_name, cfg, meta = case_config(
            case,
            steps=args.steps,
            sample_every=args.sample_every,
            save_every=args.save_every,
            dataset_config=args.dataset_config,
            output_dir=args.output_dir,
        )
        cfg_path = GENERATED_DIR / f"{variant_name}.toml"
        _write_flat_toml(cfg_path, cfg, meta)
        cmd = build_cmd(variant_name, preset=args.preset, queue=args.queue)
        printable = "PRESET=" + shlex.quote(args.preset) + " " + " ".join(
            shlex.quote(part) for part in cmd
        )
        print(f"[{idx:02d}] {case['name']}")
        print(f"     {case['desc']}")
        print(f"     config: {cfg_path.relative_to(ROOT)}")
        print(f"     cmd: {printable}")
        if args.run:
            env = os.environ.copy()
            env["PRESET"] = args.preset
            subprocess.run(cmd, cwd=ROOT, env=env, check=True)
        print("")

    if not args.run:
        print("💡 已生成配置并打印命令；加 --run 才会实际训练。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
